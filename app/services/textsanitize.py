"""
Очистка свободного текста, который вводит пользователь (водитель/владелец).

Зачем. Боты рендерят сообщения с parse_mode=HTML. Если водитель введёт
в «Откуда/Куда/Груз» или в описание расхода что-то вроде
`<a href="...">клик</a>`, то владельцу придёт сообщение ОТ БОТА с настоящей
кликабельной ссылкой — тот же приём, каким рассылают спам-ссылки на казино.

Решение. У названий мест, грузов и заметок нет причин содержать угловые
скобки, поэтому вырезаем `<` и `>` прямо на вводе. Тогда текст безопасен
сразу в обеих поверхностях:
  - в боте (HTML) — без `<` нельзя собрать тег;
  - на сайте (Jinja и так экранирует, двойного экранирования не будет —
    мы убираем символы, а не заменяем на сущности).
"""
from __future__ import annotations

import re


def clean_user_text(value: str | None) -> str:
    """Обрезать пробелы и убрать угловые скобки (защита от HTML-инъекции)."""
    if not value:
        return ""
    return value.replace("<", "").replace(">", "").strip()


_WHITESPACE = re.compile(r"\s+")


def origin_key(value: str | None) -> str:
    """Ключ склада: по нему склады считаются ОДНИМ и тем же.

    ⚠️ Одна функция на всё: показ списка на /routes, перестановка ▲▼, добавление
    маршрута и папки складов в боте водителя. Разъедутся — на экране будет две
    одинаковые с виду папки, а перестановка внутри них перестанет работать.

    Схлопываем ЛЮБЫЕ пробелы, а не только крайние. Владелец набирает названия
    руками и вставляет из переписки: «Соф.60. 24.10» с двойным пробелом внутри
    или с неразрывным пробелом (он приезжает копипастом) — это тот же склад,
    но для базы это разные строки. Именно так на экране появились две папки
    с одинаковым названием: новый маршрут заводил себе новую группу вместо
    того, чтобы встать в существующую.
    """
    return _WHITESPACE.sub(" ", (value or "").replace("\u00a0", " ")).strip()
